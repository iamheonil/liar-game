package com.liargame.domain.game;

/**
 * 라운드가 어떻게 끝났는지.
 *
 * <p>승패({@link Winner})만으로는 결과 화면에 무슨 일이 있었는지 설명할 수 없음. 예를 들어
 * "최후 투표가 부결되어 살아남음"과 "시민을 처형했는데 라이어가 아니었음"은 둘 다 라이어 승리지만
 * 전혀 다른 이야기임. 그 차이를 보존하기 위해 종료 사유를 따로 남김.
 */
public enum RoundEnding {

    /** 과반 득표자가 없어 아무도 지목되지 않음. */
    NO_MAJORITY,

    /** 지목은 됐지만 최후 투표가 부결되어 처형되지 않음. */
    ACQUITTED,

    /** 처형했는데 라이어가 아니었음. */
    WRONG_EXECUTION,

    /** 라이어를 처형함. 이 뒤에 제시어 맞히기가 이어짐. */
    LIAR_EXECUTED,

    /** 라이어가 중도 이탈해 라운드가 성립하지 않음. */
    ABORTED
}
